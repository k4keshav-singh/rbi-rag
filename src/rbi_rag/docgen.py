"""Generate the parts of the documentation that must not be typed by hand.

Rule 1 of this project is that no number appears in README or results/ unless
a script in this repository produced it. Discipline is a weak way to enforce
that: the README's results table is regenerated from ``results/*.csv`` instead,
spliced between markers, so a figure can only get there by being measured.

The same mechanism keeps the DECISIONS index in step with its entries, which
is a smaller problem of the same shape -- a hand-maintained index of 36 entries
is an index that is wrong.

Run with ``uv run poe docs``. ``--check`` fails instead of writing, which is
what CI would use to catch a stale README.
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from rbi_rag.config import PROJECT_ROOT

GENERATED_NOTE = "generated by `uv run poe docs` -- do not edit by hand"

RESULTS_BEGIN = f"<!-- BEGIN results ({GENERATED_NOTE}) -->"
RESULTS_END = "<!-- END results -->"
DECISIONS_BEGIN = f"<!-- BEGIN index ({GENERATED_NOTE}) -->"
DECISIONS_END = "<!-- END index -->"

#: Written where a measurement does not exist yet. Never a blank, which reads
#: like zero, and never an estimate.
TODO = "TODO"

#: Order the result tables appear in, when present.
RESULT_FILES = ("retrieval.csv", "generation.csv")

_DECISION_HEADING = re.compile(r"^## (\d{4}) — (.+)$", re.MULTILINE)
_DECISION_PHASE = re.compile(r"\*\*Phase:\*\*\s*(\w+)")


class MarkerError(RuntimeError):
    """The document is missing the markers the generated block goes between."""


@dataclass(frozen=True)
class Decision:
    number: str
    title: str
    phase: str | None

    @property
    def anchor(self) -> str:
        """GitHub's heading anchor for `## NNNN — Title`.

        Derived from the rendered heading, em dash included, because that is
        what GitHub slugs. It lowercases, drops anything that is not a word
        character, space or hyphen, then turns **each** space into a hyphen --
        it does not collapse runs. So `0014 — onnxruntime ...` becomes
        `0014--onnxruntime-...` with a double hyphen where the em dash was.
        Building the slug from number and title separately produced a single
        hyphen and an anchor that silently did not resolve.
        """
        slug = f"{self.number} — {self.title}".lower()
        slug = re.sub(r"[^\w\s-]", "", slug)
        return re.sub(r"\s", "-", slug)


# -- splicing ----------------------------------------------------------------


def splice(document: str, begin: str, end: str, block: str) -> str:
    """Replace whatever sits between the markers, leaving them in place."""
    start = document.find(begin)
    stop = document.find(end)
    if start == -1 or stop == -1 or stop < start:
        raise MarkerError(f"missing or reversed markers: {begin!r} .. {end!r}")
    return document[: start + len(begin)] + "\n\n" + block.strip() + "\n\n" + document[stop:]


# -- results -----------------------------------------------------------------


def render_csv_table(path: Path, max_rows: int | None = None) -> str:
    """One results CSV as a markdown table.

    Empty cells become TODO: a CSV writes an unmeasured metric as an empty
    field, and an empty markdown cell reads like a measurement of nothing.
    """
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        return f"_`{path.name}` has no rows._"

    columns = list(rows[0])
    shown = rows if max_rows is None else rows[:max_rows]

    lines = [
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join("---" for _ in columns) + " |",
    ]
    for row in shown:
        lines.append("| " + " | ".join((row.get(c) or TODO) for c in columns) + " |")

    if max_rows is not None and len(rows) > max_rows:
        lines.append("")
        lines.append(f"_Showing {max_rows} of {len(rows)} rows; see `results/{path.name}`._")
    return "\n".join(lines)


def render_results(results_dir: Path, max_rows: int | None = None) -> str:
    """The README's Results section, built from whatever has been measured."""
    present = [results_dir / name for name in RESULT_FILES]
    present = [path for path in present if path.exists()]

    if not present:
        return (
            f"**{TODO}** — no measured results yet.\n\n"
            "Results need a downloaded corpus and a human-verified evaluation "
            "set. Once both exist, run `uv run poe eval`; this section is "
            "regenerated from `results/*.csv` by `uv run poe docs` and is never "
            "written by hand."
        )

    blocks: list[str] = []
    for path in present:
        heading = path.stem.replace("_", " ").title()
        blocks.append(f"### {heading}\n\n{render_csv_table(path, max_rows)}")

    blocks.append(
        "Generated from `results/*.csv`. Retrieval figures are deterministic "
        "and reproduce exactly; generation figures replay from a response "
        "cache and re-sample when it is cleared."
    )
    return "\n\n".join(blocks)


# -- decisions ---------------------------------------------------------------


def parse_decisions(text: str) -> list[Decision]:
    """Every `## NNNN — Title` entry, with the phase it belongs to."""
    decisions: list[Decision] = []
    matches = list(_DECISION_HEADING.finditer(text))
    for index, match in enumerate(matches):
        stop = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        body = text[match.end() : stop]
        phase_match = _DECISION_PHASE.search(body)
        decisions.append(
            Decision(
                number=match.group(1),
                title=match.group(2).strip(),
                phase=phase_match.group(1) if phase_match else None,
            )
        )
    return decisions


def render_decision_index(decisions: Sequence[Decision]) -> str:
    """A navigable index. 36 entries over 1000 lines needs one."""
    if not decisions:
        return "_No decisions recorded yet._"

    lines = ["| # | Decision | Phase |", "| --- | --- | --- |"]
    for decision in decisions:
        phase = decision.phase or TODO
        lines.append(f"| {decision.number} | [{decision.title}](#{decision.anchor}) | {phase} |")
    return "\n".join(lines)


# -- driving -----------------------------------------------------------------


def update_file(path: Path, begin: str, end: str, block: str) -> bool:
    """Splice the block in. Returns True when the file changed."""
    original = path.read_text(encoding="utf-8")
    updated = splice(original, begin, end, block)
    if updated == original:
        return False
    path.write_text(updated, encoding="utf-8", newline="\n")
    return True


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="rbi-rag docs", description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if anything is out of date instead of rewriting it",
    )
    parser.add_argument(
        "--max-rows",
        type=int,
        default=None,
        help="truncate result tables; omit to show every arm",
    )
    args = parser.parse_args(argv)

    readme = PROJECT_ROOT / "README.md"
    decisions_path = PROJECT_ROOT / "DECISIONS.md"
    results_dir = PROJECT_ROOT / "results"

    targets = [
        (
            readme,
            RESULTS_BEGIN,
            RESULTS_END,
            render_results(results_dir, args.max_rows),
            "README results",
        ),
        (
            decisions_path,
            DECISIONS_BEGIN,
            DECISIONS_END,
            render_decision_index(parse_decisions(decisions_path.read_text(encoding="utf-8"))),
            "DECISIONS index",
        ),
    ]

    stale: list[str] = []
    for path, begin, end, block, label in targets:
        try:
            if args.check:
                current = path.read_text(encoding="utf-8")
                if splice(current, begin, end, block) != current:
                    stale.append(label)
            elif update_file(path, begin, end, block):
                print(f"updated {label}")
            else:
                print(f"{label} already current")
        except MarkerError as exc:
            sys.stderr.write(f"{path.name}: {exc}\n")
            return 2

    if stale:
        sys.stderr.write(f"out of date: {', '.join(stale)}. Run `uv run poe docs`.\n")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
